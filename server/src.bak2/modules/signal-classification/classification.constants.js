/**
 * Signal Classification Constants
 *
 * @module signalforge/server/modules/signal-classification/constants
 */
const CLASSIFICATION_EVENTS = Object.freeze({
  CLASSIFICATION_STARTED: 'classification.started',
  CLASSIFICATION_COMPLETED: 'classification.completed',
  CLASSIFICATION_FAILED: 'classification.failed',
  CLASSIFICATION_UNCERTAIN: 'classification.uncertain',
  CLASSIFIER_THRESHOLD_HIT: 'classification.threshold_hit',
});
const CLASSIFICATION_TYPES = Object.freeze({
  NEW_TRADE: 'NEW_TRADE',
  TRADE_MANAGEMENT: 'TRADE_MANAGEMENT',
  MARKET_ANALYSIS: 'MARKET_ANALYSIS',
  NEWS: 'NEWS',
  EDUCATION: 'EDUCATION',
  ADVERTISEMENT: 'ADVERTISEMENT',
  CONVERSATION: 'CONVERSATION',
  UNKNOWN: 'UNKNOWN',
});
const CLASSIFICATION_TYPE_VALUES = Object.freeze(
  Object.values(CLASSIFICATION_TYPES),
);
const EXECUTABLE_CLASSIFICATIONS = Object.freeze([
  CLASSIFICATION_TYPES.NEW_TRADE,
  CLASSIFICATION_TYPES.TRADE_MANAGEMENT,
]);
const NON_EXECUTABLE_CLASSIFICATIONS = Object.freeze([
  CLASSIFICATION_TYPES.MARKET_ANALYSIS,
  CLASSIFICATION_TYPES.NEWS,
  CLASSIFICATION_TYPES.EDUCATION,
  CLASSIFICATION_TYPES.ADVERTISEMENT,
  CLASSIFICATION_TYPES.CONVERSATION,
  CLASSIFICATION_TYPES.UNKNOWN,
]);
const CLASSIFIER_KINDS = Object.freeze({
  RULE_BASED: 'RULE_BASED',
  AI: 'AI',
  HYBRID: 'HYBRID',
  MANUAL: 'MANUAL',
});
const DEFAULT_CLASSIFIER_KIND = CLASSIFIER_KINDS.HYBRID;
const DEFAULT_MIN_CONFIDENCE = 0.7;
const DEFAULT_HIGH_CONFIDENCE = 0.9;
const DEFAULT_LOW_CONFIDENCE = 0.5;
const DEFAULT_RULE_BASED_THRESHOLD = 0.6;
const DEFAULT_AI_THRESHOLD = 0.5;
const MAX_MESSAGE_LENGTH_FOR_CLASSIFICATION = 8000;
const CLASSIFICATION_TIMEOUT_MS = 15000;
function isExecutable(classification) {
  return EXECUTABLE_CLASSIFICATIONS.includes(classification);
}
function isNonExecutable(classification) {
  return NON_EXECUTABLE_CLASSIFICATIONS.includes(classification);
}
function isValidClassification(classification) {
  return CLASSIFICATION_TYPE_VALUES.includes(classification);
}
module.exports.CLASSIFICATION_EVENTS = CLASSIFICATION_EVENTS;
module.exports.CLASSIFICATION_TYPES = CLASSIFICATION_TYPES;
module.exports.CLASSIFICATION_TYPE_VALUES = CLASSIFICATION_TYPE_VALUES;
module.exports.EXECUTABLE_CLASSIFICATIONS = EXECUTABLE_CLASSIFICATIONS;
module.exports.NON_EXECUTABLE_CLASSIFICATIONS = NON_EXECUTABLE_CLASSIFICATIONS;
module.exports.CLASSIFIER_KINDS = CLASSIFIER_KINDS;
module.exports.DEFAULT_CLASSIFIER_KIND = DEFAULT_CLASSIFIER_KIND;
module.exports.DEFAULT_MIN_CONFIDENCE = DEFAULT_MIN_CONFIDENCE;
module.exports.DEFAULT_HIGH_CONFIDENCE = DEFAULT_HIGH_CONFIDENCE;
module.exports.DEFAULT_LOW_CONFIDENCE = DEFAULT_LOW_CONFIDENCE;
module.exports.DEFAULT_RULE_BASED_THRESHOLD = DEFAULT_RULE_BASED_THRESHOLD;
module.exports.DEFAULT_AI_THRESHOLD = DEFAULT_AI_THRESHOLD;
module.exports.MAX_MESSAGE_LENGTH_FOR_CLASSIFICATION = MAX_MESSAGE_LENGTH_FOR_CLASSIFICATION;
module.exports.CLASSIFICATION_TIMEOUT_MS = CLASSIFICATION_TIMEOUT_MS;
module.exports.isExecutable = isExecutable;
module.exports.isNonExecutable = isNonExecutable;
module.exports.isValidClassification = isValidClassification;
