const CONSENSUS_EVENTS = Object.freeze({
  CONSENSUS_STARTED: 'consensus.started',
  CONSENSUS_REACHED: 'consensus.reached',
  CONSENSUS_FAILED: 'consensus.failed',
  CONSENSUS_CONFLICT_DETECTED: 'consensus.conflict.detected',
  CONSENSUS_INSUFFICIENT_PARTICIPANTS: 'consensus.insufficient_participants',
  CONSENSUS_MEMBER_ADDED: 'consensus.member.added',
  CONSENSUS_VOTE_CAST: 'consensus.vote.cast',
  CONSENSUS_DECISION_MADE: 'consensus.decision.made',
});
const CONSENSUS_OUTCOMES = Object.freeze({
  REACHED: 'REACHED',
  FAILED: 'FAILED',
  INSUFFICIENT_PARTICIPANTS: 'INSUFFICIENT_PARTICIPANTS',
  CONFLICT: 'CONFLICT',
  ERROR: 'ERROR',
});
const CONSENSUS_DIRECTIONS = Object.freeze({
  BUY: 'BUY',
  SELL: 'SELL',
  NO_CONSENSUS: 'NO_CONSENSUS',
});
const VOTING_STRATEGIES = Object.freeze({
  SIMPLE_MAJORITY: 'SIMPLE_MAJORITY',
  WEIGHTED_BY_CONFIDENCE: 'WEIGHTED_BY_CONFIDENCE',
  WEIGHTED_BY_REPUTATION: 'WEIGHTED_BY_REPUTATION',
  SUPER_MAJORITY: 'SUPER_MAJORITY',
  UNANIMOUS: 'UNANIMOUS',
});
const VOTING_STRATEGY_VALUES = Object.freeze(Object.values(VOTING_STRATEGIES));
const DEFAULT_CONSENSUS_WINDOW_MINUTES = 5;
const DEFAULT_MINIMUM_PARTICIPANTS = 2;
const DEFAULT_MINIMUM_AGREEMENT = 0.6;
const DEFAULT_HIGH_CONFIDENCE_THRESHOLD = 0.8;
const DEFAULT_SUPER_MAJORITY_THRESHOLD = 0.75;
const DEFAULT_REPUTATION_WEIGHT = 1.0;
const DEFAULT_CONFIDENCE_WEIGHT = 1.0;
const DEFAULT_VOTE_WEIGHT = 1.0;
const MAX_PARTICIPANTS = 100;
const MAX_WINDOW_MINUTES = 60;
function isValidVotingStrategy(strategy) {
  return VOTING_STRATEGY_VALUES.includes(strategy);
}
function isValidConsensusOutcome(outcome) {
  return Object.values(CONSENSUS_OUTCOMES).includes(outcome);
}
