export const EVENT_ACTOR_VALUES = Object.freeze(Object.values(EVENT_ACTORS));

export function isValidReplayType(type) {
  return REPLAY_TYPE_VALUES.includes(type);
}

export function isValidTimelineEventType(type) {
  return TIMELINE_EVENT_TYPE_VALUES.includes(type);
}

export function isValidActor(actor) {
  return EVENT_ACTOR_VALUES.includes(actor);
}