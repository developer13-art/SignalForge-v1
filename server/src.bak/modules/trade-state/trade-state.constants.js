export function isValidTradeState(state) {
  return TRADE_STATE_VALUES.includes(state);
}

export function isValidTradeActor(actor) {
  return TRADE_ACTOR_VALUES.includes(actor);
}

export function isValidTradeEvent(event) {
  return TRADE_EVENT_VALUES.includes(event);
}

export function isTerminalState(state) {
  return TERMINAL_TRADE_STATES.includes(state);
}

export function isActiveState(state) {
  return ACTIVE_TRADE_STATES.includes(state);
}

export function isValidTransition(fromState, toState) {
  const allowed = VALID_TRADE_TRANSITIONS[fromState];
  if (!allowed) {
    return false;
  }
  return allowed.includes(toState);
}

export function getEventSeverity(eventType) {
  return TRADE_EVENT_SEVERITY[eventType] || 'info';
}