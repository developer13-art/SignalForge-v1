export const TERMINAL_SIGNAL_STATUSES = Object.freeze([
  SIGNAL_STATUSES.VALIDATION_FAILED,
  SIGNAL_STATUSES.DUPLICATE,
  SIGNAL_STATUSES.RISK_REJECTED,
  SIGNAL_STATUSES.EXECUTED,
  SIGNAL_STATUSES.EXECUTION_FAILED,
  SIGNAL_STATUSES.ARCHIVED,
]);

export function isTerminalSignalStatus(status) {
  return TERMINAL_SIGNAL_STATUSES.includes(status);
}

export function isValidSignalStatus(status) {
  return SIGNAL_STATUS_VALUES.includes(status);
}